-- ============================================================
-- TB_ESTACAO_CAPITAL
-- ============================================================
CREATE TABLE IF NOT EXISTS public.tb_estacao_capital
(cd_estacao    integer GENERATED BY DEFAULT AS IDENTITY,
 cd_capital    integer      NOT NULL,
 wigos         varchar(60)  NOT NULL,
 nome_estacao  varchar(100) NOT NULL,
 status        boolean      NOT NULL DEFAULT true,
 CONSTRAINT pk_tb_estacao_capital PRIMARY KEY (cd_estacao),
 CONSTRAINT fk_tb_estacao_capital FOREIGN KEY (cd_capital) REFERENCES public.tb_capital (cd_capital),
 CONSTRAINT uq_tb_estacao_capital_wigos UNIQUE (wigos)
);


-- ============================================================
-- TB_TEMPERATURA
-- ============================================================
CREATE TABLE IF NOT EXISTS public.tb_temperatura
(cd_temperatura  integer GENERATED BY DEFAULT AS IDENTITY,
 cd_capital      integer NOT NULL,
 temperatura     numeric(5, 2),
 dt_referencia   timestamp with time zone NOT NULL,
 dt_atualizacao  timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status          boolean NOT NULL DEFAULT true,
CONSTRAINT pk_tb_temperatura PRIMARY KEY (cd_temperatura),
CONSTRAINT fk_tb_temperatura_capital FOREIGN KEY (cd_capital) REFERENCES public.tb_capital (cd_capital),
CONSTRAINT uq_tb_temperatura_capital_referencia UNIQUE (cd_capital, dt_referencia),
CONSTRAINT ck_tb_temperatura_valor CHECK (temperatura IS NULL OR temperatura BETWEEN -90 AND 70)
);

-- ============================================================
-- TB_FERIADO
-- ============================================================
CREATE TABLE IF NOT EXISTS public.tb_feriado
(cd_feriado      integer GENERATED BY DEFAULT AS IDENTITY,
 cd_capital      integer      NOT NULL,
 id_api          uuid         NOT NULL,
 dt_feriado      date         NOT NULL,
 nome            varchar(150) NOT NULL,
 tipo            varchar(20)  NOT NULL,
 uf              char(2),
 codigo_ibge     varchar(10),
 bancario        boolean      NOT NULL DEFAULT false,
 descricao       text,
 dt_atualizacao  timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT pk_tb_feriado PRIMARY KEY (cd_feriado),
CONSTRAINT fk_tb_feriado_capital FOREIGN KEY (cd_capital)REFERENCES tb_capital (cd_capital),
CONSTRAINT uq_tb_feriado_capital_api UNIQUE (cd_capital, id_api)
);


