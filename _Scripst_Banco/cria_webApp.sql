-- ============================================================
-- TB_MOEDA
-- ============================================================
CREATE TABLE IF NOT EXISTS public.tb_moeda
(cd_moeda        integer GENERATED BY DEFAULT AS IDENTITY,
 moeda           varchar(4)      NOT NULL,
 valor           numeric(18, 5)  NOT NULL DEFAULT 0,
 status          boolean         NOT NULL DEFAULT false,
 dt_referencia   timestamp with time zone NOT NULL,
 dt_atualizacao  timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT pk_tb_moeda PRIMARY KEY (cd_moeda),
 CONSTRAINT uq_tb_moeda_referencia UNIQUE (moeda, dt_referencia),
 CONSTRAINT ck_tb_moeda_codigo CHECK (char_length(moeda) = 4),
 CONSTRAINT ck_tb_moeda_valor CHECK (valor >= 0)
);


