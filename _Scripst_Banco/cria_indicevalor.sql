BEGIN;

-- 01. TABELAS INDEPENDENTES E CADASTRAIS

CREATE TABLE public.tb_usuario (
    cd_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login varchar(100) NOT NULL,
    senha_hash text NOT NULL,
    ativo boolean NOT NULL DEFAULT true,
    dt_cadastro timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dt_ultimo_acesso timestamptz,
    CONSTRAINT uq_tb_usuario_login UNIQUE (login),
    CONSTRAINT ck_tb_usuario_login CHECK (btrim(login) <> ''),
    CONSTRAINT ck_tb_usuario_senha CHECK (btrim(senha_hash) <> '')
);

CREATE TABLE public.tb_contato (
    cd_contato integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nm_contato varchar(80) NOT NULL,
    email varchar(120) NOT NULL,
    celular varchar(20) NOT NULL,
    comentario varchar(200) NOT NULL,
    indicadores jsonb NOT NULL DEFAULT '[]'::jsonb,
    dt_cadastro timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tb_contato_email UNIQUE (email),
    CONSTRAINT uq_tb_contato_celular UNIQUE (celular),
    CONSTRAINT ck_tb_contato_indicadores CHECK (jsonb_typeof(indicadores) = 'array')
);

CREATE TABLE public.tb_logacesso (
    cd_logacesso integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    dt_acesso timestamp NOT NULL,
    ip varchar(45) NOT NULL,
    metodo varchar(10),
    rota varchar(255),
    status_http integer,
    referer varchar(500),
    user_agent varchar(500),
    navegador varchar(50),
    dispositivo varchar(50),
    bot boolean NOT NULL DEFAULT false,
    cidade varchar(100),
    uf varchar(50),
    pais varchar(50),
    provedor varchar(150),
    dt_cadastro timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.tb_indicador_info (
    cd_indicador integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nm_indicador varchar(50) NOT NULL UNIQUE,
    titulo varchar(150) NOT NULL,
    descricao text NOT NULL,
    periodicidade varchar(30),
    fonte varchar(150),
    url_fonte text,
    fl_ativo boolean NOT NULL DEFAULT true,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.tb_capital (
    cd_capital integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade varchar(50) NOT NULL,
    cidade_busca varchar(50) NOT NULL,
    uf char(2) NOT NULL,
    regiao varchar(20) NOT NULL,
    cd_ibge varchar(10) NOT NULL,
    status boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_tb_capital_cidade_uf UNIQUE (cidade, uf),
    CONSTRAINT uq_tb_capital_cidade_busca UNIQUE (cidade_busca),
    CONSTRAINT uq_tb_capital_cd_ibge UNIQUE (cd_ibge),
    CONSTRAINT ck_tb_capital_regiao CHECK (regiao IN ('Brasil', 'Norte', 'Nordeste', 'Centro-Oeste', 'Sudeste', 'Sul'))
);

-- 02. TABELAS DE INDICADORES
CREATE TABLE public.tb_indicador (
    cd_registro bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cd_indicador int4 NOT NULL CONSTRAINT fk_tb_indicador_info REFERENCES public.tb_indicador_info(cd_indicador),
    valor numeric(18,5) NOT NULL,
    status boolean NOT NULL DEFAULT true,
    dt_referencia date NOT NULL,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tb_indicador_referencia UNIQUE (cd_indicador, dt_referencia)
);

CREATE TABLE public.tb_moeda (
    cd_moeda integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moeda varchar(5) NOT NULL,
    valor numeric(18,5) NOT NULL DEFAULT 0,
    status boolean NOT NULL DEFAULT false,
    dt_referencia timestamptz NOT NULL,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tb_moeda_referencia UNIQUE (moeda, dt_referencia),
    CONSTRAINT ck_tb_moeda_codigo CHECK (char_length(moeda) IN (3, 5)),
    CONSTRAINT ck_tb_moeda_valor CHECK (valor >= 0)
);


CREATE TABLE tb_ibovespa (
    cd_ibovespa integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pontos numeric(12,2) NOT NULL,
    variacao numeric(8,2) NOT NULL,
    variacao_pontos numeric(12,2) NOT NULL,
    abertura numeric(12,2),
    maxima numeric(12,2),
    minima numeric(12,2),
    fechamento_anterior numeric(12,2),
    status boolean NOT NULL DEFAULT TRUE,
    dt_pregao date NOT NULL,
    dt_referencia timestamptz NOT NULL,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tb_ibovespa_pregao UNIQUE (dt_pregao),
    CONSTRAINT uq_tb_ibovespa_referencia UNIQUE (dt_referencia)
);




CREATE TABLE public.tb_pib_valores (
    cd_pib_valor bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cd_setor integer NOT NULL,
    nm_setor varchar(150) NOT NULL,
    valor_milhoes numeric(18,2) NOT NULL,
    dt_referencia date NOT NULL,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_pib_valores UNIQUE (cd_setor, dt_referencia)
);

-- 03. TABELAS DEPENDENTES DE TB_CAPITAL

CREATE TABLE public.tb_estacao_capital (
    cd_estacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cd_capital integer NOT NULL CONSTRAINT fk_tb_estacao_capital REFERENCES public.tb_capital(cd_capital),
    wigos varchar(60) NOT NULL,
    nome_estacao varchar(100) NOT NULL,
    status boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_tb_estacao_capital_wigos UNIQUE (wigos)
);

CREATE TABLE public.tb_temperatura (
    cd_temperatura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cd_capital integer NOT NULL CONSTRAINT fk_tb_temperatura_capital REFERENCES public.tb_capital(cd_capital),
    temperatura numeric(5,2),
    dt_referencia timestamptz NOT NULL,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_tb_temperatura_capital_referencia UNIQUE (cd_capital, dt_referencia),
    CONSTRAINT ck_tb_temperatura_valor CHECK (temperatura IS NULL OR temperatura BETWEEN -90 AND 70)
);

CREATE TABLE public.tb_feriado (
    cd_feriado integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cd_capital integer NOT NULL CONSTRAINT fk_tb_feriado_capital REFERENCES public.tb_capital(cd_capital),
    id_api uuid NOT NULL,
    dt_feriado date NOT NULL,
    nome varchar(150) NOT NULL,
    tipo varchar(20) NOT NULL,
    uf char(2),
    codigo_ibge varchar(10),
    bancario boolean NOT NULL DEFAULT false,
    descricao text,
    dt_atualizacao timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tb_feriado_capital_api UNIQUE (cd_capital, id_api)
);

